def verify_phase1_schema() -> None:
    """Print a concise Phase 1 verification summary for the developer."""
    assumptions = PlantDesignAssumptions()
    delta_t = assumptions.sand_temp_max_operating_c - assumptions.sand_temp_min_operating_c
    q_max_kwh = (
        assumptions.sand_mass_kg
        * assumptions.sand_specific_heat_kj_per_kg_k
        * delta_t
        / 3600.0
    )
    print("=== EcoFarm Circular — Phase 1 System Boundary Verification ===")
    print(f"Site Reference       : {assumptions.site_name}")
    print(f"Time Resolution      : {assumptions.sampling_interval_minutes} min (UTC)")
    print(f"Defined Variables    : {len(VARIABLE_SCHEMA)}")
    print(f"PLC Safety Interlocks: {len(PLC_HARDWIRED_INTERLOCKS)}")
    print(f"Design Sand Storage  : {q_max_kwh:.2f} kWh usable ({assumptions.sand_temp_min_operating_c:.0f}–{assumptions.sand_temp_max_operating_c:.0f} °C)")
    for prov in DataProvenance:
        count = sum(1 for v in VARIABLE_SCHEMA.values() if v.provenance == prov)
        print(f"  - {prov.value:<18}: {count} variables")


if __name__ == "__main__":
    verify_phase1_schema()
