"""
EcoFarm Circular — Phase 1 Configuration, System Boundaries & Data Schema
=========================================================================

This module defines the engineering boundaries, baseline pilot-plant design
assumptions, PLC safety interlocks, and formal data dictionary for the
EcoFarm Circular AI-Based Intelligent Energy Management System.

IMPORTANT SCIENTIFIC DISCIPLINE:
- Parameters in `PlantDesignAssumptions` are explicit engineering assumptions
  for simulation and sizing until pilot-plant commissioning measurements exist.
- Every variable in `VARIABLE_SCHEMA` is tagged with its exact provenance:
    * MEASURED_EXTERNAL : Real historical observations (e.g. PVGIS / weather).
    * SIMULATED         : Generated by documented thermodynamic equations.
    * CALCULATED        : Deterministic engineering identity from inputs.
    * PREDICTED_ML      : Output of a trained Machine Learning model (Phase 5+).
"""

