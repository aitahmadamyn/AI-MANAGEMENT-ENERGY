"""
EcoFarm Circular — Phase 3: Thermodynamic Models (Dryer, Solar Thermal & NCG)
=============================================================================

Implements documented physical equations for:
1. Biomass Dryer Thermal Demand (wet-basis mass balance + psychrometric coupling
   + non-overlapping First-Law enthalpy balance).
2. Solar Thermal Collector Array (ISO 9806 / EN 12975 collector curve, strictly
   separate from PV electrical power).
3. Slow Pyrolysis Non-Condensable Gas (NCG) Heat Recovery (mass flow, configurable
   LHV / composition, combustion efficiency, and HX effectiveness).

PROVENANCE NOTE:
All outputs generated by this module are `simulated_physics` values driven by
real hourly meteorological inputs from Phase 2.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Dict, Optional


@dataclass(frozen=True)
class DryerParameters:
    """Configurable biomass dryer parameters (literature + scenario assumptions)."""

    batch_mass_kg: float = 250.0
    batch_duration_hours: float = 4.0
    initial_moisture_frac: float = 0.45  # Wet basis
    target_moisture_frac: float = 0.12   # Wet basis
    biomass_inlet_temp_c: float = 22.0
    biomass_outlet_temp_c: float = 65.0
    dryer_chamber_temp_c: float = 85.0
    exhaust_air_temp_c: float = 60.0
    exhaust_max_rh_pct: float = 80.0
    min_delta_omega: float = 0.004       # Minimum humidity pickup (kg_H2O / kg_da)
    dryer_shell_ua_w_per_k: float = 25.0 # Conductive/convective shell heat loss
    hx_duct_efficiency: float = 0.85     # Indirect HTF-to-air HX & duct efficiency

    # Literature thermophysical constants
    cp_dry_biomass_kj_kg_k: float = 1.45
    cp_liquid_water_kj_kg_k: float = 4.186
    cp_dry_air_kj_kg_k: float = 1.006
    cp_water_vapor_kj_kg_k: float = 1.86


@dataclass(frozen=True)
class SolarThermalParameters:
    """Configurable EN 12975 / ISO 9806 solar thermal collector parameters."""

    collector_area_m2: float = 35.0
    optical_efficiency_eta0: float = 0.74
    heat_loss_a1_w_m2_k: float = 3.5
    heat_loss_a2_w_m2_k2: float = 0.015
    collector_mean_fluid_temp_c: float = 95.0


@dataclass(frozen=True)
class PyrolysisNcgParameters:
    """
    Configurable NCG heat recovery parameters.
    Does NOT assume a fixed NCG production rate or composition without data;
    allows either explicit gas composition or configurable scenario bounds.
    """

    dry_biomass_feed_rate_kg_h: float = 55.0
    ncg_mass_yield_frac: float = 0.22        # kg_ncg / kg_dry_biomass
    ncg_lhv_kj_per_kg: float = 9500.0        # Configurable (typical range 6000-14000 kJ/kg)
    burner_combustion_eff: float = 0.88
    heat_exchanger_eff: float = 0.82


def barometric_pressure_kpa(elevation_m: float = 366.0) -> float:
    """Standard atmosphere barometric pressure (kPa) at site elevation (m)."""
    return 101.325 * ((1.0 - 2.25577e-5 * elevation_m) ** 5.25588)


def saturation_vapor_pressure_kpa(temp_c: float) -> float:
    """Magnus-Tetens saturation vapor pressure of water (kPa) for T in °C."""
    return 0.61078 * math.exp((17.27 * temp_c) / (temp_c + 237.3))


def humidity_ratio_kg_per_kg(temp_c: float, rh_pct: float, p_atm_kpa: float) -> float:
    """Psychrometric humidity ratio (kg_water / kg_dry_air)."""
    rh_clamped = max(0.0, min(100.0, rh_pct))
    p_sat = saturation_vapor_pressure_kpa(temp_c)
    p_v = (rh_clamped / 100.0) * p_sat
    # Guard denominator against physical saturation boiling edge
    denom = max(1.0, p_atm_kpa - p_v)
    return 0.621945 * (p_v / denom)


def latent_heat_vaporization_kj_kg(temp_c: float) -> float:
    """Linearized steam-table latent heat of water vaporization (kJ/kg)."""
    return 2501.3 - 2.369 * temp_c


def compute_dryer_hourly_demand(
    ambient_temp_c: float,
    ambient_rh_pct: float,
    is_operating: bool,
    params: DryerParameters,
    elevation_m: float = 366.0,
) -> Dict[str, float]:
    """
    Compute hourly biomass dryer mass flows and non-overlapping thermal demand (kW).

    Control volume spans indirect HTF-to-air HX + drying chamber so latent heat,
    sensible biomass/water heating, incoming ambient air heating, and shell losses
    are accounted for exactly once (zero double-counting).
    """
    if not is_operating or params.batch_mass_kg <= 0.0:
        return {
            "m_wet_kg_s": 0.0,
            "m_dry_kg_s": 0.0,
            "m_water_out_kg_s": 0.0,
            "m_evap_kg_s": 0.0,
            "mass_balance_residual_kg_s": 0.0,
            "omega_amb": 0.0,
            "omega_out": 0.0,
            "m_dry_air_kg_s": 0.0,
            "q_evap_vapor_kw": 0.0,
            "q_bio_sensible_kw": 0.0,
            "q_water_rem_sensible_kw": 0.0,
            "q_air_exhaust_kw": 0.0,
            "q_shell_loss_kw": 0.0,
            "dryer_thermal_demand_kw": 0.0,
        }

    if not (0.0 < params.target_moisture_frac < params.initial_moisture_frac < 1.0):
        raise ValueError("Require 0 < target_moisture_frac < initial_moisture_frac < 1.")

    # 1. Mass balance (kg/s)
    m_wet = params.batch_mass_kg / (params.batch_duration_hours * 3600.0)
    m_dry = m_wet * (1.0 - params.initial_moisture_frac)
    m_water_in = m_wet * params.initial_moisture_frac
    m_water_out = m_dry * (params.target_moisture_frac / (1.0 - params.target_moisture_frac))
    m_evap = m_water_in - m_water_out
    mass_residual = abs(m_wet - (m_dry + m_water_out + m_evap))

    # 2. Psychrometrics coupled to Settat ambient weather
    p_atm = barometric_pressure_kpa(elevation_m)
    omega_amb = humidity_ratio_kg_per_kg(ambient_temp_c, ambient_rh_pct, p_atm)
    omega_out = humidity_ratio_kg_per_kg(
        params.exhaust_air_temp_c, params.exhaust_max_rh_pct, p_atm
    )
    delta_omega = max(omega_out - omega_amb, params.min_delta_omega)
    m_da = m_evap / delta_omega

    # 3. Non-overlapping First-Law energy terms (kW = kJ/s)
    t_bio_in = ambient_temp_c if params.biomass_inlet_temp_c is None else params.biomass_inlet_temp_c
    dt_bio = max(0.0, params.biomass_outlet_temp_c - t_bio_in)

    h_fg = latent_heat_vaporization_kj_kg(params.exhaust_air_temp_c)
    q_evap_vapor = m_evap * (
        params.cp_liquid_water_kj_kg_k * max(0.0, params.exhaust_air_temp_c - t_bio_in) + h_fg
    )
    q_bio_sensible = m_dry * params.cp_dry_biomass_kj_kg_k * dt_bio
    q_water_rem_sensible = m_water_out * params.cp_liquid_water_kj_kg_k * dt_bio

    cp_moist_in = params.cp_dry_air_kj_kg_k + omega_amb * params.cp_water_vapor_kj_kg_k
    q_air_exhaust = m_da * cp_moist_in * max(0.0, params.exhaust_air_temp_c - ambient_temp_c)

    q_shell_loss = (
        params.dryer_shell_ua_w_per_k * max(0.0, params.dryer_chamber_temp_c - ambient_temp_c)
    ) / 1000.0

    q_useful_total = (
        q_evap_vapor + q_bio_sensible + q_water_rem_sensible + q_air_exhaust + q_shell_loss
    )
    dryer_demand_kw = q_useful_total / params.hx_duct_efficiency

    return {
        "m_wet_kg_s": m_wet,
        "m_dry_kg_s": m_dry,
        "m_water_out_kg_s": m_water_out,
        "m_evap_kg_s": m_evap,
        "mass_balance_residual_kg_s": mass_residual,
        "omega_amb": omega_amb,
        "omega_out": omega_out,
        "m_dry_air_kg_s": m_da,
        "q_evap_vapor_kw": q_evap_vapor,
        "q_bio_sensible_kw": q_bio_sensible,
        "q_water_rem_sensible_kw": q_water_rem_sensible,
        "q_air_exhaust_kw": q_air_exhaust,
        "q_shell_loss_kw": q_shell_loss,
        "dryer_thermal_demand_kw": dryer_demand_kw,
    }


def compute_solar_thermal_kw(
    irradiance_wm2: float,
    ambient_temp_c: float,
    params: SolarThermalParameters,
) -> float:
    """
    ISO 9806 / EN 12975 collector thermal output (kW_th).
    Kept strictly separate from PV electrical power.
    """
    if irradiance_wm2 <= 0.0 or params.collector_area_m2 <= 0.0:
        return 0.0

    dt = max(0.0, params.collector_mean_fluid_temp_c - ambient_temp_c)
    net_flux_w_m2 = (
        params.optical_efficiency_eta0 * irradiance_wm2
        - params.heat_loss_a1_w_m2_k * dt
        - params.heat_loss_a2_w_m2_k2 * (dt ** 2)
    )
    return max(0.0, (params.collector_area_m2 * net_flux_w_m2) / 1000.0)


def ncg_lhv_from_mass_composition(species_mass_fracs: Dict[str, float]) -> float:
    """
    Optional helper to compute NCG LHV (kJ/kg) from measured gas mass fractions.
    Standard LHVs (kJ/kg): CO=10100, H2=120000, CH4=50000, C2H4=47200, CO2=0, N2=0.
    """
    lhv_table = {
        "CO": 10100.0,
        "H2": 120000.0,
        "CH4": 50000.0,
        "C2H4": 47200.0,
        "CO2": 0.0,
        "N2": 0.0,
    }
    return sum(frac * lhv_table.get(sp, 0.0) for sp, frac in species_mass_fracs.items())


def compute_ncg_recovered_heat_kw(
    burner_active: bool,
    params: PyrolysisNcgParameters,
    species_mass_fracs: Optional[Dict[str, float]] = None,
) -> Dict[str, float]:
    """
    Compute recoverable thermal power (kW_th) from pyrolysis NCG combustion.
    """
    if not burner_active:
        return {"m_ncg_kg_s": 0.0, "lhv_ncg_kj_kg": 0.0, "recovered_thermal_power_kw": 0.0}

    m_pyr_dry_kg_s = params.dry_biomass_feed_rate_kg_h / 3600.0
    m_ncg_kg_s = m_pyr_dry_kg_s * params.ncg_mass_yield_frac
    lhv = (
        ncg_lhv_from_mass_composition(species_mass_fracs)
        if species_mass_fracs is not None
        else params.ncg_lhv_kj_per_kg
    )
    q_rec_kw = (
        m_ncg_kg_s
        * lhv
        * params.burner_combustion_eff
        * params.heat_exchanger_eff
    )
    return {
        "m_ncg_kg_s": m_ncg_kg_s,
        "lhv_ncg_kj_kg": lhv,
        "recovered_thermal_power_kw": q_rec_kw,
    }


