def train_and_evaluate_dryer_models() -> Dict[str, _Any]:
    """Train, validate, compare, and persist Model 2 (Biomass Dryer Thermal Demand)."""
    from src.solar_model import _write_svg_actual_vs_pred_and_residuals, _write_svg_feature_importance

    train_split = generate_multi_feedstock_dryer_split(_PROCESSED_DIR / "train_2020_2021.csv", samples_per_feedstock=2000, seed=101)
    val_split = generate_multi_feedstock_dryer_split(_PROCESSED_DIR / "val_2022.csv", samples_per_feedstock=750, seed=202)
    test_split = generate_multi_feedstock_dryer_split(_PROCESSED_DIR / "test_2023.csv", samples_per_feedstock=750, seed=303)

    X_tr, y_tr = train_split["X"], train_split["y"]
    X_va, y_va = val_split["X"], val_split["y"]
    X_te, y_te = test_split["X"], test_split["y"]

    # Baselines
    tr_mean = sum(y_tr) / len(y_tr)
    mean_baseline = {
        "key": "baseline_mean",
        "name": "Baseline: Training Mean",
        "short_label": "Mean\nBaseline",
        "kind": "baseline",
        "train": _regression_metrics(y_tr, [tr_mean] * len(y_tr)),
        "val": _regression_metrics(y_va, [tr_mean] * len(y_va)),
        "test": _regression_metrics(y_te, [tr_mean] * len(y_te)),
        "overfit_status": "Baseline Reference",
        "selected": False,
    }
    evap_baseline = {
        "key": "baseline_latent_only",
        "name": "Baseline: Latent Evap Only (m_evap·h_fg / η)",
        "short_label": "Latent\nOnly",
        "kind": "baseline",
        "train": _regression_metrics(y_tr, train_split["evap_baseline_preds"]),
        "val": _regression_metrics(y_va, val_split["evap_baseline_preds"]),
        "test": _regression_metrics(y_te, test_split["evap_baseline_preds"]),
        "overfit_status": "Systematic Negative Bias (Omits Air Heating)",
        "selected": False,
    }

    candidates = [
        (
            "linear_regression",
            "Linear Regression (OLS + StandardScaler)",
            "Linear\nRegression",
            _LinearRegression(l2_reg=1e-8, scale_features=True),
            {"scale_features": True, "l2_reg": 1e-8},
        ),
        (
            "decision_tree",
            "Decision Tree Regressor",
            "Decision\nTree",
            _DecisionTreeRegressor(max_depth=10, min_samples_split=10, min_samples_leaf=4, max_bins=64, random_state=42),
            {"max_depth": 10, "min_samples_leaf": 4, "max_bins": 64},
        ),
        (
            "random_forest",
            "Random Forest Regressor",
            "Random\nForest",
            _RandomForestRegressor(n_estimators=22, max_depth=11, min_samples_split=8, min_samples_leaf=3, max_features_ratio=0.8, subsample_ratio=0.85, max_bins=64, random_state=42),
            {"n_estimators": 22, "max_depth": 11, "min_samples_leaf": 3},
        ),
        (
            "gradient_boosting",
            "Gradient Boosting Regressor",
            "Gradient\nBoosting",
            _GradientBoostingRegressor(n_estimators=65, learning_rate=0.12, max_depth=4, min_samples_split=10, min_samples_leaf=4, subsample=0.85, max_bins=64, random_state=42),
            {"n_estimators": 65, "learning_rate": 0.12, "max_depth": 4},
        ),
    ]

    ml_results: _List[Dict[str, _Any]] = []
    fitted_unified: Dict[str, _Any] = {}

    for key, display_name, short_lbl, est, params in candidates:
        est.fit(X_tr, y_tr)
        fitted_unified[key] = est

        p_tr = [max(0.0, v) for v in est.predict(X_tr)]
        p_va = [max(0.0, v) for v in est.predict(X_va)]
        p_te = [max(0.0, v) for v in est.predict(X_te)]

        m_tr = _regression_metrics(y_tr, p_tr)
        m_va = _regression_metrics(y_va, p_va)
        m_te = _regression_metrics(y_te, p_te)

        gap = (m_va["rmse"] - m_tr["rmse"]) / max(m_tr["rmse"], 1e-6)
        status = "Mild Overfit (Monitor)" if (gap > 0.35 and m_va["rmse"] - m_tr["rmse"] > 0.25) else "Well-Generalized"

        artifact = {
            "model_key": key,
            "model_name": display_name,
            "target": "dryer_thermal_demand_kw",
            "target_provenance": "simulated_physics",
            "feature_names": DRYER_FEATURE_NAMES,
            "hyperparameters": params,
            "estimator": est,
            "feedstocks_supported": list(BIOMASS_FEEDSTOCK_LIBRARY.keys()),
        }
        _save_model_artifact(artifact, _MODELS_DIR / f"dryer_unified_{key}.pkl")

        ml_results.append(
            {
                "key": key,
                "name": display_name,
                "short_label": short_lbl,
                "kind": "ml_model",
                "hyperparameters": params,
                "train": m_tr,
                "val": m_va,
                "test": m_te,
                "overfit_status": status,
                "selected": False,
            }
        )

    best_entry = min(ml_results, key=lambda r: (r["val"]["rmse"], r["val"]["mae"]))
    best_entry["selected"] = True
    best_key = best_entry["key"]
    best_unified_est = fitted_unified[best_key]

    best_artifact = _load_model_artifact(_MODELS_DIR / f"dryer_unified_{best_key}.pkl")
    _save_model_artifact(best_artifact, _MODELS_DIR / "dryer_best_unified_model.pkl")

    # Compare Single Unified Model vs Separate Per-Feedstock Models (using selected architecture)
    best_te_preds_all = [max(0.0, v) for v in best_unified_est.predict(X_te)]
    best_va_preds_all = [max(0.0, v) for v in best_unified_est.predict(X_va)]
    per_feedstock_comparison: _List[Dict[str, _Any]] = []
    short_names = {"olive_pomace": "Olive Pomace", "wheat_straw": "Wheat Straw", "wood_chips": "Wood Chips"}

    for fid, spec in BIOMASS_FEEDSTOCK_LIBRARY.items():
        # Unified predictions sliced for this feedstock on identical Val/Test sets
        va_yt_f = [yv for yv, f in zip(y_va, val_split["feedstocks"]) if f == fid]
        va_yp_unified = [pv for pv, f in zip(best_va_preds_all, val_split["feedstocks"]) if f == fid]
        te_yt_f = [yv for yv, f in zip(y_te, test_split["feedstocks"]) if f == fid]
        te_yp_unified = [pv for pv, f in zip(best_te_preds_all, test_split["feedstocks"]) if f == fid]

        m_uni_va = _regression_metrics(va_yt_f, va_yp_unified)
        m_uni_te = _regression_metrics(te_yt_f, te_yp_unified)

        # Train separate dedicated model of the same winning family on this feedstock only
        X_tr_f, y_tr_f = _subset_by_feedstock(train_split, fid, drop_one_hot=True)
        X_va_f, _ = _subset_by_feedstock(val_split, fid, drop_one_hot=True)
        X_te_f, _ = _subset_by_feedstock(test_split, fid, drop_one_hot=True)

        if best_key == "linear_regression":
            sep_est: _Any = _LinearRegression(l2_reg=1e-8, scale_features=True)
        elif best_key == "decision_tree":
            sep_est = _DecisionTreeRegressor(max_depth=10, min_samples_split=10, min_samples_leaf=4, max_bins=64, random_state=42)
        elif best_key == "random_forest":
            sep_est = _RandomForestRegressor(n_estimators=22, max_depth=11, min_samples_split=8, min_samples_leaf=3, max_features_ratio=0.8, subsample_ratio=0.85, max_bins=64, random_state=42)
        else:
            sep_est = _GradientBoostingRegressor(n_estimators=65, learning_rate=0.12, max_depth=4, min_samples_split=10, min_samples_leaf=4, subsample=0.85, max_bins=64, random_state=42)

        sep_est.fit(X_tr_f, y_tr_f)
        sep_va_preds = [max(0.0, v) for v in sep_est.predict(X_va_f)]
        sep_te_preds = [max(0.0, v) for v in sep_est.predict(X_te_f)]
        m_sep_va = _regression_metrics(va_yt_f, sep_va_preds)
        m_sep_te = _regression_metrics(te_yt_f, sep_te_preds)

        _save_model_artifact(
            {
                "feedstock_id": fid,
                "model_key": best_key,
                "feature_names": DRYER_FEATURE_NAMES[5:],
                "target_provenance": "simulated_physics",
                "estimator": sep_est,
            },
            _MODELS_DIR / f"dryer_separate_{fid}.pkl",
        )

        per_feedstock_comparison.append(
            {
                "feedstock_id": fid,
                "display_name": spec.display_name,
                "short_name": short_names[fid],
                "cp_kj_kg_k": spec.cp_dry_biomass_kj_kg_k,
                "bulk_density_kg_m3": spec.bulk_density_kg_m3,
                "n_train": len(y_tr_f),
                "n_val": len(va_yt_f),
                "n_test": len(te_yt_f),
                "unified_val_rmse": m_uni_va["rmse"],
                "unified_test_rmse": m_uni_te["rmse"],
                "unified_test_mae": m_uni_te["mae"],
                "unified_test_r2": m_uni_te["r2"],
                "separate_val_rmse": m_sep_va["rmse"],
                "separate_test_rmse": m_sep_te["rmse"],
                "separate_test_mae": m_sep_te["mae"],
                "separate_test_r2": m_sep_te["r2"],
                "delta_rmse_unified_minus_sep": round(m_uni_te["rmse"] - m_sep_te["rmse"], 5),
            }
        )

    res_stats = _residual_summary(y_te, best_te_preds_all)
    perm_imp = _permutation_importance(
        best_unified_est,
        X_te,
        y_te,
        DRYER_FEATURE_NAMES,
        n_repeats=5,
        seed=42,
        clip_min=0.0,
    )
    for item in perm_imp:
        item["label"] = DRYER_FEATURE_LABELS.get(item["feature"], item["feature"])

    step = max(1, len(y_te) // 450)
    scatter_sample = [
        {
            "feedstock": test_split["feedstocks"][i],
            "actual": round(y_te[i], 4),
            "predicted": round(best_te_preds_all[i], 4),
            "residual": round(y_te[i] - best_te_preds_all[i], 4),
        }
        for i in range(0, len(y_te), step)
    ]

    all_models = [mean_baseline, evap_baseline] + ml_results

    _write_svg_dryer_comparison(all_models, per_feedstock_comparison, _FIGURES_DIR / "12_dryer_model_comparison.svg")
    _write_svg_actual_vs_pred_and_residuals(
        best_entry["name"],
        scatter_sample,
        res_stats,
        "kW_th",
        "Model 2: Biomass Dryer Thermal Demand",
        _FIGURES_DIR / "13_dryer_actual_vs_pred_residuals.svg",
    )
    _write_svg_feature_importance(
        perm_imp,
        DRYER_FEATURE_LABELS,
        "Model 2: Dryer Thermal Demand Permutation Importance (2023 Test)",
        f"Selected Unified Model: {best_entry['name']} · Target provenance: simulated_physics",
        "kW_th",
        _FIGURES_DIR / "14_dryer_feature_importance.svg",
    )

    avg_uni_rmse = sum(r["unified_test_rmse"] for r in per_feedstock_comparison) / len(per_feedstock_comparison)
    avg_sep_rmse = sum(r["separate_test_rmse"] for r in per_feedstock_comparison) / len(per_feedstock_comparison)
    if avg_uni_rmse <= avg_sep_rmse * 1.15:
        multi_feedstock_verdict = (
            f"A single unified multi-feedstock {best_entry['name']} is appropriate and recommended: "
            f"across the 3 feedstocks, average 2023 Test RMSE is {avg_uni_rmse:.3f} kW_th vs. {avg_sep_rmse:.3f} kW_th "
            f"for separate models, because physical drying demand shares common latent-evaporation and psychrometric "
            f"laws captured cleanly via feedstock properties (Cp, bulk density) and one-hot identifiers."
        )
    else:
        multi_feedstock_verdict = (
            f"Separate per-feedstock models achieve noticeably lower 2023 Test RMSE ({avg_sep_rmse:.3f} vs. {avg_uni_rmse:.3f} kW_th) "
            f"due to distinct operating moisture envelopes across olive pomace, wheat straw, and wood chips."
        )

    return {
        "model_id": "Model 2 — Biomass Dryer Thermal Demand Prediction",
        "target_variable": "dryer_thermal_demand_kw",
        "target_unit": "kW_th",
        "target_provenance": "simulated_physics",
        "simulated_label_disclaimer": (
            "All Model 2 targets are deterministic outputs of the Phase 3 thermodynamic balance "
            "(compute_dryer_hourly_demand) coupled to real Settat 2020–2023 weather. They are explicitly "
            "labeled simulated_physics rather than experimental pilot-plant calorimeter measurements."
        ),
        "splits": {
            "train_2020_2021": {"rows": len(X_tr), "per_feedstock": 2000},
            "val_2022": {"rows": len(X_va), "per_feedstock": 750},
            "test_2023": {"rows": len(X_te), "per_feedstock": 750},
        },
        "feedstocks": [
            {
                "id": s.feedstock_id,
                "name": s.display_name,
                "cp_kj_kg_k": s.cp_dry_biomass_kj_kg_k,
                "bulk_density_kg_m3": s.bulk_density_kg_m3,
                "batch_mass_range_kg": [s.batch_mass_min_kg, s.batch_mass_max_kg],
                "init_moisture_range_pct": [round(s.init_moisture_min * 100, 1), round(s.init_moisture_max * 100, 1)],
                "target_moisture_range_pct": [round(s.target_moisture_min * 100, 1), round(s.target_moisture_max * 100, 1)],
            }
            for s in BIOMASS_FEEDSTOCK_LIBRARY.values()
        ],
        "features": DRYER_FEATURE_NAMES,
        "selected_model_key": best_key,
        "selected_model_name": best_entry["name"],
        "models": all_models,
        "unified_vs_per_feedstock": per_feedstock_comparison,
        "multi_feedstock_verdict": multi_feedstock_verdict,
        "test_residual_summary": res_stats,
        "permutation_importance": perm_imp,
        "scatter_sample": scatter_sample,
        "saved_artifacts": [
            "models/dryer_unified_linear_regression.pkl",
            "models/dryer_unified_decision_tree.pkl",
            "models/dryer_unified_random_forest.pkl",
            "models/dryer_unified_gradient_boosting.pkl",
            "models/dryer_best_unified_model.pkl",
            "models/dryer_separate_olive_pomace.pkl",
            "models/dryer_separate_wheat_straw.pkl",
            "models/dryer_separate_wood_chips.pkl",
        ],
    }


def predict_dryer_thermal_demand_kw(
    feedstock_id: str,
    batch_mass_kg: float,
    initial_moisture_pct: float,
    target_moisture_pct: float,
    ambient_temp_c: float,
    ambient_rh_pct: float,
    batch_duration_hours: float = 4.0,
    dryer_chamber_temp_c: float = 85.0,
    hx_duct_efficiency: float = 0.85,
    model_path: _Path = _MODELS_DIR / "dryer_best_unified_model.pkl",
) -> float:
    """Reusable multi-feedstock ML inference wrapper for Phase 6 & Phase 7."""
    artifact = _load_model_artifact(model_path)
    vec = [
        encode_dryer_features(
            feedstock_id=feedstock_id,
            batch_mass_kg=batch_mass_kg,
            batch_duration_hours=batch_duration_hours,
            initial_moisture_pct=initial_moisture_pct,
            target_moisture_pct=target_moisture_pct,
            ambient_temp_c=ambient_temp_c,
            ambient_rh_pct=ambient_rh_pct,
            dryer_chamber_temp_c=dryer_chamber_temp_c,
            hx_duct_efficiency=hx_duct_efficiency,
        )
    ]
    return max(0.0, float(artifact["estimator"].predict(vec)[0]))


